def tr(lang):
    """Return a lookup function for one language; unknown keys fall back to Spanish and then to the key."""
    table, fallback = TEXT.get(lang, TEXT["es"]), TEXT["es"]
    return lambda key: table.get(key, fallback.get(key, key))


